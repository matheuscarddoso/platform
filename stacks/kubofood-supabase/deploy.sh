#!/usr/bin/env bash
# Deploy (or update) the kubofood Supabase stack on the platform server.
#
#   rsync -a --delete --exclude volumes/db/data --exclude volumes/storage --exclude .env \
#     stacks/kubofood-supabase/ root@HOST:/opt/stacks/kubofood-supabase/
#   ssh root@HOST /opt/stacks/kubofood-supabase/deploy.sh
#
# First run: generates .env (0600) with fresh internal secrets. The project's
# JWT secret and the anon/service keys are read from /root/sbmig (copied from
# Supabase Cloud so every existing key stays valid). Later runs keep .env as is.
set -Eeuo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
umask 077

if [[ ! -f .env ]]; then
  [[ -s /root/sbmig/jwt_secret && -s /root/sbmig/keys.env ]] || { echo "missing /root/sbmig/jwt_secret or keys.env" >&2; exit 1; }
  anon=$(sed -n 's/^NEXT_PUBLIC_SUPABASE_ANON_KEY=//p' /root/sbmig/keys.env)
  service=$(sed -n 's/^SUPABASE_SERVICE_ROLE_KEY=//p' /root/sbmig/keys.env)
  rand() { openssl rand -hex "$1"; }
  cat > .env <<EOF
# Generated by deploy.sh on $(date -u +%FT%TZ). Do not commit.
API_HOST=api.kubofood.app
SUPABASE_PUBLIC_URL=https://api.kubofood.app
SITE_URL=https://www.kubofood.app

POSTGRES_HOST=db
POSTGRES_PORT=5432
POSTGRES_DB=postgres
POSTGRES_PASSWORD=$(rand 32)

JWT_SECRET=$(cat /root/sbmig/jwt_secret)
JWT_EXPIRY=3600
ANON_KEY=$anon
SERVICE_ROLE_KEY=$service

PGRST_DB_SCHEMAS=public,graphql_public
PGRST_DB_MAX_ROWS=1000
PGRST_DB_EXTRA_SEARCH_PATH=public,extensions

SECRET_KEY_BASE=$(rand 48)
REALTIME_DB_ENC_KEY=$(rand 8)
PG_META_CRYPTO_KEY=$(rand 32)
S3_PROTOCOL_ACCESS_KEY_ID=$(rand 16)
S3_PROTOCOL_ACCESS_KEY_SECRET=$(rand 32)

DASHBOARD_USERNAME=supabase
DASHBOARD_PASSWORD=$(rand 24)
EOF
  echo "generated .env"
fi

mkdir -p volumes/db/data volumes/storage
docker compose pull --quiet
docker compose up -d --remove-orphans

echo "waiting for services to become healthy..."
for i in $(seq 1 60); do
  unhealthy=$(docker compose ps --format '{{.Name}} {{.Health}}' | awk '$2 != "healthy" {print $1}')
  [[ -z "$unhealthy" ]] && { echo "all services healthy"; docker compose ps --format '  {{.Name}}\t{{.Image}}\t{{.Health}}'; exit 0; }
  sleep 5
done
echo "not healthy after 5 min: $unhealthy" >&2
docker compose ps --format '  {{.Name}}\t{{.Health}}\t{{.Status}}' >&2
exit 1
